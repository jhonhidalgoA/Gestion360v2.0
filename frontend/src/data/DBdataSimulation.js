// --- Helpers de aplanado (temporales, para probar el Select mientras no hay filtro real) ---
const flattenDba = (dbaSource) =>
  Object.entries(dbaSource).flatMap(([grado, items]) =>
    items.map((item) => ({
      value: item.id,
      label: `${grado.replace("grado", "Grado ")} — ${item.enunciado}`,
    }))
  );

const flattenEvidencias = (dbaSource) =>
  Object.values(dbaSource)
    .flat()
    .flatMap((item) =>
      item.evidencias.map((evidencia, i) => ({
        value: `${item.id}-ev${i}`,
        label: evidencia,
      }))
    );

